#!/usr/bin/env node
// Writes a git-ignored .env for the demo server from near-cli-rs legacy keychain files
// (~/.near-credentials/testnet). Picks the agent's FUNCTION-CALL key, never its full-access key.
// Usage: node scripts/make-env.js <owner-account.testnet> [contract-account.testnet]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const owner = process.argv[2];
if (!owner || !owner.endsWith('.testnet')) { console.error('usage: node scripts/make-env.js <owner>.testnet [vault.<owner>.testnet]'); process.exit(1); }
const contract = process.argv[3] || `vault.${owner}`;
const agent = process.env.AGENT_ACCOUNT_ID || `agent.${owner}`;
const credDir = process.env.NEAR_CREDENTIALS_DIR || path.join(os.homedir(), '.near-credentials', 'testnet');
const rpc = process.env.NEAR_RPC_URL || 'https://test.rpc.fastnear.com';

async function keys(account) {
  const r = await fetch(rpc, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'query', params: { request_type: 'view_access_key_list', finality: 'final', account_id: account } }) });
  return (await r.json()).result.keys;
}

const ownerKey = JSON.parse(fs.readFileSync(path.join(credDir, `${owner}.json`), 'utf8')).private_key;
const fc = (await keys(agent)).find((k) => k.access_key.permission?.FunctionCall?.receiver_id === contract);
if (!fc) { console.error(`no function-call key on ${agent} for ${contract}`); process.exit(1); }
const fcFile = path.join(credDir, agent, `${fc.public_key.replace(':', '_')}.json`);
const agentKey = JSON.parse(fs.readFileSync(fcFile, 'utf8')).private_key;

const out = [
  '# Generated by scripts/make-env.js — NEVER commit this file.',
  'NEAR_NETWORK=testnet',
  `LEASHPAY_CONTRACT=${contract}`,
  `AGENT_ACCOUNT_ID=${agent}`,
  `AGENT_PRIVATE_KEY=${agentKey}`,
  `OWNER_ACCOUNT_ID=${owner}`,
  `OWNER_PRIVATE_KEY=${ownerKey}`,
  'ENABLE_OWNER_ACTIONS=true',
  '# Optional: GEMINI_API_KEY=... (falls back to a rule-based parser when unset)',
  '',
].join('\n');
fs.writeFileSync(path.resolve('.env'), out, { mode: 0o600 });
console.log(`.env written for contract ${contract} (agent key = function-call key ${fc.public_key.slice(0, 16)}…, permission: ${JSON.stringify(fc.access_key.permission.FunctionCall.method_names)})`);
